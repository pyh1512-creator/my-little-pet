export const CHARACTER_LIST: CharacterDefinition[] = Object.values(CHARACTERS);

export function getEvolutionStage(charId: CharacterId, level: number) {
  const char = CHARACTERS[charId];
  let current = char.evolutions[0];
  for (const evo of char.evolutions) {
    if (level >= evo.minLevel) {
      current = evo;
    }
  }
  return current;
}
